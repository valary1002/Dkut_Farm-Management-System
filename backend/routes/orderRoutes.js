const express = require('express')
const controller = require('../controllers/orderController')
const { authenticate, authorize } = require('../middleware/authMiddleware')
const router = express.Router()
router.post('/', authenticate, authorize('CUSTOMER'), controller.create)
router.get('/my', authenticate, authorize('CUSTOMER'), controller.mine)
router.get('/attention/list', authenticate, authorize('ADMIN', 'STAFF'), controller.attention)
router.get('/:id', authenticate, authorize('CUSTOMER', 'ADMIN', 'STAFF'), controller.detail)
router.get('/', authenticate, authorize('ADMIN'), controller.all)
router.post('/checkout', authenticate, authorize('CUSTOMER'), controller.checkout)
router.patch('/:id/confirm', authenticate, authorize('ADMIN'), controller.confirmOrder)
router.patch('/:id/cancel', authenticate, authorize('CUSTOMER'), controller.cancelForCustomer)
router.patch('/:id/received', authenticate, authorize('CUSTOMER'), controller.receiveOrder)
router.patch('/:id/problem', authenticate, authorize('CUSTOMER'), controller.reportProblem)
router.patch('/:id/status', authenticate, authorize('ADMIN', 'STAFF'), controller.updateStatus)
module.exports = router
